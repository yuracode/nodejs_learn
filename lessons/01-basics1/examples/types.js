const price = 120; // 数値
const item = "りんご"; // 文字列
const inStock = true; // 真偽値（true か false）

console.log(typeof price);
console.log(typeof item);
console.log(typeof inStock);

// 数値どうしの + は足し算
console.log(10 + 5);

// 文字列が混ざると、+ は「つなげる」になる
console.log("10" + 5);

// 文字列を数値に直してから足す
console.log(Number("10") + 5);
